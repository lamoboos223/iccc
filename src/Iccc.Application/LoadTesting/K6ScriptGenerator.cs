namespace Iccc.Application.LoadTesting;

public sealed record K6Endpoint(string Method, string Path, decimal WeightPercent);

public sealed record K6ScriptRequest
{
    public required string BaseUrl { get; init; }
    public required int TargetRps { get; init; }
    public required int RampUpSeconds { get; init; }
    public required int SustainSeconds { get; init; }
    public required int RampDownSeconds { get; init; }
    public required IReadOnlyList<K6Endpoint> Endpoints { get; init; }
    public decimal? MaxP95LatencyMs { get; init; }
    public decimal MaxErrorRate { get; init; } = 0.01m;
    public bool AuthenticationRequired { get; init; }
    public int PayloadBytes { get; init; } = 128;
}

public static class K6ScriptGenerator
{
    public static string Generate(K6ScriptRequest request)
    {
        var preAllocated = Math.Max(50, request.TargetRps / 20);
        var maxVus = preAllocated * 4;
        var endpoints = request.Endpoints.Count == 0
            ? new[] { new K6Endpoint("GET", "/", 100) }
            : request.Endpoints.ToArray();
        var endpointLiteral = string.Join(",\n    ", endpoints.Select(endpoint =>
            $"{{ method: {Js(endpoint.Method)}, path: {Js(endpoint.Path)}, weight: {endpoint.WeightPercent.ToString(System.Globalization.CultureInfo.InvariantCulture)} }}"));
        var p95 = request.MaxP95LatencyMs?.ToString(System.Globalization.CultureInfo.InvariantCulture) ?? "500";
        var errorRate = request.MaxErrorRate.ToString(System.Globalization.CultureInfo.InvariantCulture);
        var auth = request.AuthenticationRequired
            ? "if (__ENV.ICCC_AUTH_TOKEN) { headers.Authorization = 'Bearer ' + __ENV.ICCC_AUTH_TOKEN; }"
            : "";

        return $$"""
            // Generated by ICCC. Requests per second are scheduled with ramping-arrival-rate.
            // Virtual users are only the pool that supplies those arrivals. They are not the workload target.
            // Credentials are read from ICCC_AUTH_TOKEN and are not written into this file.
            import http from 'k6/http';
            import { check } from 'k6';

            const baseUrl = __ENV.ICCC_BASE_URL || {{Js(request.BaseUrl)}};
            const endpoints = [
                {{endpointLiteral}}
            ];

            export const options = {
              scenarios: {
                certified_workload: {
                  executor: 'ramping-arrival-rate',
                  startRate: 1,
                  timeUnit: '1s',
                  preAllocatedVUs: {{preAllocated}},
                  maxVUs: {{maxVus}},
                  stages: [
                    { target: {{request.TargetRps}}, duration: '{{request.RampUpSeconds}}s' },
                    { target: {{request.TargetRps}}, duration: '{{request.SustainSeconds}}s' },
                    { target: 0, duration: '{{request.RampDownSeconds}}s' },
                  ],
                },
              },
              thresholds: {
                http_req_failed: ['rate<{{errorRate}}'],
                http_req_duration: ['p(95)<{{p95}}'],
                dropped_iterations: ['count<1'],
              },
            };

            function pick() {
              const roll = Math.random() * 100;
              let cursor = 0;
              for (const endpoint of endpoints) {
                cursor += endpoint.weight;
                if (roll <= cursor) return endpoint;
              }
              return endpoints[endpoints.length - 1];
            }

            export default function () {
              const endpoint = pick();
              const nonce = `${Date.now()}-${Math.floor(Math.random() * 100000)}`;
              const headers = { 'Content-Type': 'application/json', 'X-Request-Nonce': nonce };
              {{auth}}
              const body = endpoint.method === 'GET' ? null : JSON.stringify({
                nonce,
                padding: 'x'.repeat({{request.PayloadBytes}}),
              });
              const response = http.request(endpoint.method, `${baseUrl}${endpoint.path}`, body, { headers, tags: { endpoint: endpoint.path } });
              check(response, { 'status is 2xx or 3xx': (item) => item.status >= 200 && item.status < 400 });
            }
            """;
    }

    private static string Js(string value)
    {
        return "'" + value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("'", "\\'", StringComparison.Ordinal) + "'";
    }
}
